#!/usr/bin/env python3
"""Build script for drift website.

Generates HTML pages from markdown and other data sources.
"""

import json
import os
import subprocess
from pathlib import Path
from datetime import datetime

# Paths
DOCS_DIR = Path("docs")
POSTS_DIR = Path("docs/_posts")
TOOLS_MD = Path("../TOOLS.md")
KNOWLEDGE_BASE_JSON = Path("docs/knowledge_base.json")

# Configuration
POSTS = [p for p in POSTS_DIR.glob("*.md") if not p.name.startswith("_")]
if not POSTS:
    raise RuntimeError(f"No markdown posts found in {POSTS_DIR}")

# Load tool inventory
def load_tools():
    """Parse TOOLS.md and return list of tools."""
    tools = []
    with open(TOOLS_MD) as f:
        lines = f.readlines()
    
    # Skip header
    in_tools = False
    for line in lines:
        line = line.strip()
        if line.startswith("## Tools"):
            in_tools = True
            continue
        if in_tools and line.startswith("## "):
            break
        if in_tools and line and not line.startswith("#"):
            tools.append(line)
    return tools

# Generate posts
def generate_posts():
    """Convert markdown posts to HTML."""
    for md_file in sorted(POSTS):
        html_file = DOCS_DIR / f"{md_file.stem}.html"
        
        # Read markdown
        with open(md_file) as f:
            body = f.read()
        
        # Convert markdown to HTML
        from markdown import markdown
        html_body = markdown(body, extensions=["fenced_code", "tables"])
        
        # Generate HTML page
        html = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{md_file.stem}</title>
    <link rel="stylesheet" href="style.css">
</head>
<body>
    <header>
        <nav>
            <a href="index.html">Home</a>
            <a href="runs.html">Runs</a>
            <a href="knowledge_base.html">Knowledge Base</a>
            <a href="tools.html">Tools</a>
        </nav>
    </header>
    <main>
        {html_body}
    </main>
    <footer>
        <p>Generated by drift build script</p>
    </footer>
</body>
</html>"""
        
        with open(html_file, "w") as f:
            f.write(html)
        print(f"Generated {html_file}")

