# Generate runs page
def generate_runs_json():
    """Generate runs.json from RUNS.md."""
    runs_file = Path("RUNS.md")
    if not runs_file.exists():
        print(f"Warning: {runs_file} not found")
        return []
    
    runs = []
    in_table = False
    
    with open(runs_file) as f:
        for line in f:
            line = line.strip()
            if line.startswith("|"):
                if not in_table:
                    # Check if this is a table header
                    parts = line.split("|")
                    if len(parts) >= 3 and parts[1].strip().isdigit():
                        in_table = True
                        continue
                else:
                    parts = line.split("|")
                    if len(parts) >= 3:
                        run_num = parts[1].strip()
                        date_str = parts[2].strip()
                        if run_num.isdigit() and date_str:
                            runs.append({
                                "run": int(run_num),
                                "date": date_str,
                                "ended": parts[3].strip() if len(parts) > 3 else "unknown",
                                "turns": int(parts[4].strip()) if len(parts) > 4 and parts[4].strip().isdigit() else 0,
                                "tokens": int(parts[5].strip()) if len(parts) > 5 and parts[5].strip().isdigit() else 0
                            })
    
    # Save to file
    with open(DOCS_DIR / "runs.json", "w") as f:
        json.dump(runs, f, indent=2)
    
    print(f"Generated runs.json with {len(runs)} runs")
    return runs

# Generate runs.html visualization
def generate_runs_page(runs):
    """Generate runs.html visualization page."""
    # Group by end type
    groups = {"stop": [], "out_of_turns": [], "error": [], "interrupt": []}
    for run in runs:
        end_type = run.get("ended", "unknown")
        if end_type in groups:
            groups[end_type].append(run)
        else:
            groups["other"].append(run)
    
    # Create SVG visualization
    svg_width = 800
    svg_height = 400
    padding = 40
    chart_width = svg_width - padding * 2
    chart_height = svg_height - padding * 2
    
    # Draw timeline
    timeline_lines = []
    current_y = padding + 20
    
    # Draw axis
    timeline_lines.append(f'<line x1="{padding}" y1="{svg_height - padding}" x2="{svg_width - padding}" y2="{svg_height - padding}" stroke="#666" stroke-width="2" />')
    
    # Draw end type markers
    colors = {"stop": "#22c55e", "out_of_turns": "#f59e0b", "error": "#ef4444", "interrupt": "#3b82f6", "other": "#6b7280"}
    y_positions = {}
    current_y = padding + 50
    for end_type, color in colors.items():
        if groups[end_type]:
            y_positions[end_type] = current_y
            timeline_lines.append(f'<rect x="{padding}" y="{current_y - 10}" width="{chart_width}" height="20" fill="{color}" opacity="0.3" />')
            timeline_lines.append(f'<text x="{padding}" y="{current_y + 5}" fill="{color}" font-size="12">{end_type}</text>')
            current_y += 30
    
    # Draw runs as marks on timeline
    marks = []
    for run in runs:
        if run["date"] in y_positions:
            x = padding + (run["run"] / 491) * chart_width
            y = y_positions[run["date"]] + 5
            end_type = run.get("ended", "other")
            color = colors.get(end_type, colors["other"])
            marks.append(f'<circle cx="{x}" cy="{y}" r="6" fill="{color}" stroke="white" stroke-width="2" data-run="{run["run"]}" data-date="{run["date"]}" data-ended="{end_type}" />')
    
    # Build HTML
    html = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Runs - Drift</title>
    <link rel="stylesheet" href="style.css">
    <style>
        .tooltip {{
            position: absolute;
            background: rgba(0, 0, 0, 0.8);
            color: white;
            padding: 10px;
            border-radius: 4px;
            font-size: 14px;
            display: none;
            pointer-events: none;
            z-index: 100;
        }}
        .tooltip strong {{
            display: block;
            margin-bottom: 4px;
        }}
    </style>
</head>
<body>
    <header>
        <nav>
            <a href="index.html">Home</a>
            <a href="runs.html">Runs</a>
            <a href="knowledge_base.html">Knowledge Base</a>
            <a href="tools.html">Tools</a>
        </nav>
    </header>
    <main>
        <h1>Run History</h1>
        <p>Total: {len(runs)} runs</p>
        <div class="timeline-container">
            <svg width="{svg_width}" height="{svg_height}" class="timeline">
                {"".join(timeline_lines)}
                {"".join(marks)}
            </svg>
        </div>
        <div id="tooltip" class="tooltip"></div>
    </main>
    <footer>
        <p>Generated by drift build script</p>
    </footer>
    <script>
        const tooltip = document.getElementById('tooltip');
        const marks = document.querySelectorAll('circle[data-run]');
        
        marks.forEach(mark => {{
            mark.addEventListener('mouseenter', (e) => {{
                const run = e.target.dataset.run;
                const date = e.target.dataset.date;
                const ended = e.target.dataset.ended;
                tooltip.innerHTML = '<strong>Run {run}</strong>{date} - {ended}';
                tooltip.style.display = 'block';
            }});
            
            mark.addEventListener('mousemove', (e) => {{
                tooltip.style.left = e.pageX + 10 + 'px';
                tooltip.style.top = e.pageY - 10 + 'px';
            }});
            
            mark.addEventListener('mouseleave', () => {{
                tooltip.style.display = 'none';
            }});
        }});
    </script>
</body>
</html>"""
    
    with open(DOCS_DIR / "runs.html", "w") as f:
        f.write(html)
    print("Generated runs.html")

